#include <iostream>  // Library for input and output

using namespace std;

int main()  // Main function
{
    int x = 12;     // integer
    char c = 'Z';   // char
    string day = "Monday";  // string
    double d = 5.2;         // double
    float a = 2.3f;         // float
    bool b = true;          // boolean

    // Display data
    cout << "Integer: \t" << x << endl;
    cout << "Character: \t" << c << endl;
    cout << "String: \t" << day << endl;
    cout << "Double: \t" << d << endl;
    cout << "Float: \t" << a << endl;
    cout << "Boolean: \t" << b << endl;
    

    return 0;  // End of program
}